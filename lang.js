const languageButtons = document.querySelectorAll('.lang-button');

function setLanguage(lang) {
    const copy = translations[lang];
    if (!copy) return;

    for (const element of document.querySelectorAll('[data-i18n]')) {
        const key = element.dataset.i18n;
        if (Object.prototype.hasOwnProperty.call(copy, key)) {
            element.textContent = copy[key];
        }
    }

    for (const attr of ['href', 'aria-label', 'alt', 'content']) {
        const dataAttr = 'data-i18n-' + attr;
        for (const element of document.querySelectorAll('[' + dataAttr + ']')) {
            const key = element.getAttribute(dataAttr);
            if (Object.prototype.hasOwnProperty.call(copy, key)) {
                element.setAttribute(attr, copy[key]);
            }
        }
    }

    document.documentElement.lang = lang;
    const navButton = document.querySelector('.menu-toggle');
    if (navButton) {
        const open = navButton.getAttribute('aria-expanded') === 'true';
        navButton.setAttribute('aria-label', copy[open ? 'menu_close' : 'menu_open']);
    }
    for (const button of languageButtons) {
        const selected = button.dataset.lang === lang;
        button.classList.toggle('is-active', selected);
        button.setAttribute('aria-pressed', String(selected));
    }

    try { localStorage.setItem('portfolio-language', lang); } catch (_) {}
}

for (const button of languageButtons) {
    button.addEventListener('click', () => setLanguage(button.dataset.lang));
}

let initialLanguage = 'en';
try {
    const saved = localStorage.getItem('portfolio-language');
    if (saved === 'fr' || saved === 'en') initialLanguage = saved;
} catch (_) {}
setLanguage(initialLanguage);


// Menu mobile
const menuToggle = document.querySelector('.menu-toggle');
const mobileNav = document.querySelector('#primary-nav');

function setMenuOpen(open) {
    if (!menuToggle || !mobileNav) return;
    mobileNav.classList.toggle('is-open', open);
    menuToggle.setAttribute('aria-expanded', String(open));
    const lang = document.documentElement.lang === 'fr' ? 'fr' : 'en';
    menuToggle.setAttribute('aria-label', translations[lang][open ? 'menu_close' : 'menu_open']);
}

if (menuToggle && mobileNav) {
    menuToggle.addEventListener('click', () => {
        setMenuOpen(menuToggle.getAttribute('aria-expanded') !== 'true');
    });

    mobileNav.querySelectorAll('a').forEach(link => {
        link.addEventListener('click', () => setMenuOpen(false));
    });

    document.addEventListener('keydown', event => {
        if (event.key === 'Escape' && menuToggle.getAttribute('aria-expanded') === 'true') {
            setMenuOpen(false);
            menuToggle.focus();
        }
    });

    document.addEventListener('click', event => {
        if (!menuToggle.contains(event.target) && !mobileNav.contains(event.target)) {
            setMenuOpen(false);
        }
    });

    window.matchMedia('(min-width: 701px)').addEventListener('change', event => {
        if (event.matches) setMenuOpen(false);
    });
}
